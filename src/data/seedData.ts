/**
 * The seeded intelligence, split by the workspace each item belongs to (via conversationId).
 * Evidence and attachments are picked by what each workspace's items and messages actually reference.
 */
export function seedIntelligenceByWorkspace() {
  const messagesByWs: Record<string, Message[]> = {
    ws_goa: SEED_MESSAGES_GOA,
    ws_flat: SEED_MESSAGES_FLAT,
    ws_project: SEED_MESSAGES_PROJECT,
  };
  const ids = Object.keys(messagesByWs);
  const group = <T extends { conversationId: string }>(items: T[]) =>
    Object.fromEntries(ids.map(id => [id, items.filter(i => i.conversationId === id)])) as Record<string, T[]>;

  const decisions = group(INITIAL_DECISIONS);
  const commitments = group(INITIAL_COMMITMENTS);
  const conflicts = group(INITIAL_CONFLICTS);

  const evidence: Record<string, Record<string, Evidence>> = {};
  const attachments: Record<string, Record<string, Attachment>> = {};
  for (const id of ids) {
    const evIds = new Set<string>([
      ...decisions[id].flatMap(d => [...d.supportingEvidenceIds, ...d.contradictingEvidenceIds, ...d.history.flatMap(h => h.evidenceIds)]),
      ...commitments[id].flatMap(c => c.evidenceIds),
      ...conflicts[id].flatMap(c => c.evidenceIds),
    ]);
    evidence[id] = Object.fromEntries(Object.entries(INITIAL_EVIDENCE).filter(([key]) => evIds.has(key)));

    const attIds = new Set(messagesByWs[id].flatMap(m => m.attachmentIds || []));
    attachments[id] = Object.fromEntries(Object.entries(ATTACHMENTS).filter(([key]) => attIds.has(key)));
  }
  return { decisions, commitments, conflicts, evidence, attachments };
}
